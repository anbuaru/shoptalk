"""Request / response models for the ShopTalk inference API (Phase 7, voice added in Phase 10).

The API takes plain text (`query`), so speech-to-text can be added in front later (Phase 10)
without changing the pipeline. `history` is optional: send back the `history_entry` of earlier
responses to ask follow-ups such as "something similar but cheaper".
"""
from __future__ import annotations

from typing import List, Literal, Optional

from pydantic import BaseModel, Field


class HistoryTurn(BaseModel):
    """
    Represents a single conversational turn in the history stack.

    Attributes:
        parsed (dict): The resolved query filters and metadata from the query parser.
        products (List[dict]): List of product dictionary representation cards shown in this turn.
    """
    parsed: dict
    products: List[dict] = Field(default_factory=list)


class RecommendRequest(BaseModel):
    """
    Inbound payload validation schema for the recommendation endpoint.

    Attributes:
        query (str): Plain-text natural language user inquiry. Constrained between 1 and 500 characters.
        history (List[HistoryTurn]): Accumulated historical context turns to assist in follow-up queries.
        session_id (str, optional): Tracking token utilized for logging telemetry cohorts.
    """
    query: str = Field(..., min_length=1, max_length=500, examples=["Show me red sneakers for men under $50"])
    history: List[HistoryTurn] = Field(default_factory=list, description="Earlier turns (last 3 are used)")
    session_id: Optional[str] = Field(None, max_length=100, description="Optional client session id, logged")


class ProductCard(BaseModel):
    """
    Standardized representation schema of an individual product returned to the UI client.

    Attributes:
        id (str): Unique product item identifier.
        title (str): Title/name of the product.
        brand (str, optional): Product brand metadata.
        price (float, optional): Sale price in USD.
        color (str, optional): Identified primary color attribute.
        product_type (str, optional): Normalized taxonomy category name.
        image_url (str, optional): Valid URL referencing the product photo thumbnail.
        link (str, optional): Target product URL redirecting via /click endpoint.
        score (float): Vector search match confidence similarity score.
        matched (dict): Boolean validation flags reflecting specific search criteria checks.
        price_unknown (bool): Flag showing if the product does not have pricing details.
    """
    id: str
    title: str = ""
    brand: Optional[str] = None
    price: Optional[float] = None
    color: Optional[str] = None
    product_type: Optional[str] = None
    image_url: Optional[str] = None
    link: Optional[str] = None
    score: float = 0.0
    matched: dict = Field(default_factory=dict)
    price_unknown: bool = False


class RecommendResponse(BaseModel):
    """
    Outbound payload structure returned by the recommendation engine.

    Attributes:
        request_id (str): Unique hash tracking token for this request instance.
        query (str): Mirror of the validated user query.
        answer (str): Fully cited, grounded natural language recommendation response.
        products (List[ProductCard]): Evaluated and filtered catalog recommendation cards.
        no_match (bool): Indicator flag if no matching products were returned by retriever.
        unmet_constraints (List[str]): List of identified filters that could not be satisfied.
        parsed (dict): The parsed query parameters generated by the semantic extraction model.
        grounding (dict): Evaluation tracking keys for hallucinated or cited records.
        llm (str, optional): Identifier of the active inference LLM model.
        latency_ms (dict): Millisecond timing intervals spent inside each processing phase.
        history_entry (HistoryTurn): Packaged history block reflecting current turn outputs.
    """
    request_id: str
    query: str
    answer: str
    products: List[ProductCard]
    no_match: bool
    unmet_constraints: List[str] = Field(default_factory=list,
                                         description="Requested attributes none of the products has, e.g. ['type']")
    parsed: dict
    grounding: dict
    llm: Optional[str] = None
    latency_ms: dict
    history_entry: HistoryTurn


class FeedbackRequest(BaseModel):
    """
    Explicit feedback logging schema capturing user-level satisfaction signals.

    Attributes:
        request_id (str): The unique request hash corresponding to the logged turn.
        rating (str): Directional evaluation status, strictly 'up' or 'down'.
        comment (str, optional): Free-form review statement.
        session_id (str, optional): Associated tracking session context.
    """
    request_id: str = Field(..., max_length=64)
    rating: Literal["up", "down"]
    comment: Optional[str] = Field(None, max_length=1000)
    session_id: Optional[str] = Field(None, max_length=100)


class HealthResponse(BaseModel):
    """
    Server status payload reporting active component states.

    Attributes:
        status (str): Current operating state ('ok', 'loading', 'error').
        llm (str, optional): Active language model signature string.
        embed_model (str, optional): Active embedding model signature string.
        index_size (int, optional): Size of the local vector database collection.
        uptime_s (float): Total runtime in seconds since the service was launched.
        error (str, optional): Exception context if status evaluates to 'error'.
    """
    status: Literal["ok", "loading", "error"]
    llm: Optional[str] = None
    embed_model: Optional[str] = None
    index_size: Optional[int] = None
    uptime_s: float
    error: Optional[str] = None
    asr: Optional[str] = Field(None, description="Speech-to-text model, when loaded (Phase 10)")
    asr_status: Optional[str] = Field(None, description="'ok' | 'loading' | 'error' | 'disabled'")
    tts: Optional[str] = Field(None, description="Text-to-speech model, when enabled (Phase 10)")
    tts_status: Optional[str] = None


# ---------------- Phase 10: voice ----------------
class TranscribeResponse(BaseModel):
    """
    Result of POST /transcribe (speech -> query text).

    Attributes:
        request_id (str): Unique id of this transcription (logged in asr.jsonl).
        text (str): The query to search: the transcript with spelled numbers turned into digits
            ("under thirty dollars" -> "under $30"). Shown to the user before searching.
        raw_text (str): The model's transcript before that normalisation.
        model (str): Speech-to-text model id.
        audio_s (float): Length of the audio in seconds.
        latency_ms (dict): decode (audio -> 16 kHz), queue (waiting for the GPU) and asr (model) times.
    """
    request_id: str
    text: str
    raw_text: str
    model: str
    audio_s: float
    latency_ms: dict


class AudioRecommendResponse(RecommendResponse):
    """POST /recommend/audio: the normal /recommend response plus the transcript that was searched."""
    transcript: str = Field(..., description="The query that was searched (normalised transcript)")
    raw_transcript: str = Field(..., description="Speech-to-text output before number normalisation")
    asr_model: str
    audio_s: float


class SpeakRequest(BaseModel):
    """POST /speak: text to read aloud (product IDs and markdown are removed, numbers spelled out)."""
    text: str = Field(..., min_length=1, max_length=2000)
